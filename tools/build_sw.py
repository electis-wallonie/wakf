#!/usr/bin/env python3
"""Regenerates sw.js with the full precache list + a content hash version. Run after any change:  python3 tools/build_sw.py"""
import hashlib, os, json
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files, h = [], hashlib.sha1()
for d in ['', 'css', 'js', 'data', 'fonts', 'icons', 'assets/reading']:
    p = os.path.join(ROOT, d)
    if not os.path.isdir(p): continue
    for f in sorted(os.listdir(p)):
        fp = os.path.join(p, f)
        if not os.path.isfile(fp) or f in ('sw.js', 'README.md', '.nojekyll') or f.startswith('.'): continue
        if d == '' and not f.endswith(('.html', '.webmanifest')): continue
        rel = (d + '/' + f) if d else f
        files.append(rel); h.update(open(fp, 'rb').read())
h.update(open(os.path.abspath(__file__), 'rb').read())  # template changes bump the version too
ver = h.hexdigest()[:10]
sw = f"""/* Wakf service worker — generated by tools/build_sw.py (do not edit by hand) */
const VERSION = 'wakf-{ver}';
const PRECACHE = {json.dumps(['./'] + files, indent=0)};
self.addEventListener('install', (e) => {{
  // the new version waits until the page asks for it ("Nouvelle version disponible — Recharger")
  // pages from the first version have no update banner: upgrade them directly once (marker cache 'wakf-meta-v2')
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(PRECACHE.map((u) => new Request(u, {{ cache: 'reload' }}))))
    .then(() => caches.has('wakf-meta-v2')).then((has) => {{ if (!has) {{ caches.open('wakf-meta-v2'); return self.skipWaiting(); }} }}));
}});
self.addEventListener('message', (e) => {{
  if (e.data && e.data.type === 'skip') self.skipWaiting();
}});
self.addEventListener('activate', (e) => {{
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== VERSION && k !== 'wakf-meta-v2' && k !== 'wakf-quran').map((k) => caches.delete(k)))).then(() => self.clients.claim()));
}});
self.addEventListener('fetch', (e) => {{
  const req = e.request;
  if (req.method === 'GET' && new URL(req.url).origin === 'https://api.quran.com') {{
    // verse translations read live from quran.com: network first, last copy kept for offline use
    e.respondWith(fetch(req).then((res) => {{ if (res.ok) {{ const copy = res.clone(); caches.open('wakf-quran').then((c) => c.put(req, copy)); }} return res; }})
      .catch(() => caches.open('wakf-quran').then((c) => c.match(req))));
    return;
  }}
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.match(req, {{ ignoreSearch: true }}).then((hit) => hit || fetch(req).then((res) => {{
    if (res.ok) {{ const copy = res.clone(); caches.open(VERSION).then((c) => c.put(req, copy)); }}
    return res;
  }}).catch(() => caches.match('./index.html'))));
}});
"""
open(os.path.join(ROOT, 'sw.js'), 'w').write(sw)
print(ver, len(files), 'files')
